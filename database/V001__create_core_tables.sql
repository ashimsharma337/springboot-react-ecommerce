-- Creates the complete commerce and storefront schema before any data migrations.
BEGIN;

-- Creates the namespace used by all application tables.
CREATE SCHEMA IF NOT EXISTS ecommerce;

-- Stores application accounts and audit timestamps used by the backend.
CREATE TABLE IF NOT EXISTS ecommerce.app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255),
    email VARCHAR(320),
    password VARCHAR(255),
    role VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE ecommerce.app_user IS 'Application accounts and authentication data.';

-- Stores catalog products, storefront fields, inventory, and product attributes.
CREATE TABLE IF NOT EXISTS ecommerce.product (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    price NUMERIC(12, 2) NOT NULL CONSTRAINT product_price_nonnegative CHECK (price >= 0),
    description TEXT,
    stock INTEGER CONSTRAINT product_stock_nonnegative CHECK (stock >= 0),
    category VARCHAR(255),
    slug VARCHAR(160),
    image_url TEXT,
    image_alt TEXT,
    rating NUMERIC(2, 1) CONSTRAINT product_rating_range CHECK (rating BETWEEN 0 AND 5),
    review_count INTEGER NOT NULL DEFAULT 0 CONSTRAINT product_review_count_nonnegative CHECK (review_count >= 0),
    badge VARCHAR(80),
    badge_tone VARCHAR(16) CONSTRAINT product_badge_tone_values
        CHECK (badge_tone IN ('blue', 'neutral', 'dark', 'sky')),
    specs TEXT,
    series VARCHAR(80),
    subcategory VARCHAR(120),
    attributes JSONB NOT NULL DEFAULT '{}'::JSONB
        CONSTRAINT product_attributes_object CHECK (jsonb_typeof(attributes) = 'object'),
    connectivities TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    finishes TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    in_stock BOOLEAN NOT NULL DEFAULT TRUE,
    noise_cancelling BOOLEAN,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE ecommerce.product IS 'Products, storefront card fields, inventory, and catalog metadata.';

-- Stores a user's selected products and quantities.
CREATE TABLE IF NOT EXISTS ecommerce.cart (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES ecommerce.app_user (user_id),
    product_id BIGINT REFERENCES ecommerce.product (product_id),
    quantity INTEGER CONSTRAINT cart_quantity_positive CHECK (quantity > 0),
    status VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE ecommerce.cart IS 'Products selected by users before checkout.';

-- Stores order totals and lifecycle status for the existing order API.
CREATE TABLE IF NOT EXISTS ecommerce.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES ecommerce.app_user (user_id),
    total_price NUMERIC(12, 2) CONSTRAINT order_total_nonnegative CHECK (total_price >= 0),
    order_date TIMESTAMP(6),
    status VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE ecommerce.orders IS 'Orders placed by application users.';

-- Stores curated category cards shown on the storefront.
CREATE TABLE IF NOT EXISTS ecommerce.storefront_category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(120) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    eyebrow VARCHAR(160) NOT NULL,
    description TEXT NOT NULL,
    unit_label VARCHAR(80) NOT NULL,
    image_url TEXT NOT NULL,
    display_order SMALLINT NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE ecommerce.storefront_category IS 'Curated category cards shown on the storefront.';

-- Links products to storefront categories while preserving category display order.
CREATE TABLE IF NOT EXISTS ecommerce.storefront_category_product (
    category_id BIGINT NOT NULL REFERENCES ecommerce.storefront_category (category_id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES ecommerce.product (product_id) ON DELETE CASCADE,
    display_order SMALLINT NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    PRIMARY KEY (category_id, product_id)
);
COMMENT ON TABLE ecommerce.storefront_category_product IS 'Ordered many-to-many links between storefront categories and products.';

-- Stores the ordered gallery images and accessible descriptions for a product.
CREATE TABLE IF NOT EXISTS ecommerce.product_gallery (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES ecommerce.product (product_id) ON DELETE CASCADE,
    image_url TEXT NOT NULL,
    alt_text TEXT NOT NULL,
    label VARCHAR(120) NOT NULL,
    display_order SMALLINT NOT NULL CHECK (display_order >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (product_id, display_order)
);
COMMENT ON TABLE ecommerce.product_gallery IS 'Ordered product images with accessible alt text and labels.';

-- Groups product specifications into ordered detail-page sections.
CREATE TABLE IF NOT EXISTS ecommerce.product_specification_group (
    group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES ecommerce.product (product_id) ON DELETE CASCADE,
    group_name VARCHAR(160) NOT NULL,
    title VARCHAR(160) NOT NULL,
    display_order SMALLINT NOT NULL CHECK (display_order >= 0),
    UNIQUE (product_id, display_order)
);
COMMENT ON TABLE ecommerce.product_specification_group IS 'Ordered specification sections belonging to a product.';

-- Stores ordered name/value pairs for each product specification section.
CREATE TABLE IF NOT EXISTS ecommerce.product_specification (
    specification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES ecommerce.product_specification_group (group_id) ON DELETE CASCADE,
    specification_name VARCHAR(160) NOT NULL,
    specification_value TEXT NOT NULL,
    display_order SMALLINT NOT NULL CHECK (display_order >= 0),
    UNIQUE (group_id, display_order)
);
COMMENT ON TABLE ecommerce.product_specification IS 'Individual product specification name and value pairs.';

-- Stores the ordered list of items included with each product.
CREATE TABLE IF NOT EXISTS ecommerce.product_box_content (
    content_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES ecommerce.product (product_id) ON DELETE CASCADE,
    title VARCHAR(160) NOT NULL,
    description TEXT NOT NULL,
    icon VARCHAR(80) NOT NULL,
    display_order SMALLINT NOT NULL CHECK (display_order >= 0),
    UNIQUE (product_id, display_order)
);
COMMENT ON TABLE ecommerce.product_box_content IS 'Ordered list of items included in a product package.';

-- Stores customer reviews and optional references to registered accounts.
CREATE TABLE IF NOT EXISTS ecommerce.product_review (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES ecommerce.product (product_id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES ecommerce.app_user (user_id) ON DELETE SET NULL,
    initials VARCHAR(12) NOT NULL,
    reviewer_name VARCHAR(160) NOT NULL,
    reviewer_role VARCHAR(160) NOT NULL,
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    review_title VARCHAR(240) NOT NULL,
    review_body TEXT NOT NULL,
    reviewed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE ecommerce.product_review IS 'Customer reviews displayed on product detail pages.';

-- Stores ordered recommendations between distinct products.
CREATE TABLE IF NOT EXISTS ecommerce.related_product (
    product_id BIGINT NOT NULL REFERENCES ecommerce.product (product_id) ON DELETE CASCADE,
    related_product_id BIGINT NOT NULL REFERENCES ecommerce.product (product_id) ON DELETE CASCADE,
    display_order SMALLINT NOT NULL CHECK (display_order >= 0),
    PRIMARY KEY (product_id, related_product_id),
    CHECK (product_id <> related_product_id),
    UNIQUE (product_id, display_order)
);
COMMENT ON TABLE ecommerce.related_product IS 'Ordered product-to-product recommendations.';

COMMIT;
